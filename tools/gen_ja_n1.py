"""Generates quizzes/05_n1/*.json (run from the repo root).

Prompts and options use the app's furigana markup {漢字|かな} directly. In each question the
correct option is listed first; write() shuffles the options (avoiding the same answer
position twice in a row) and checks every point has at least two questions.
"""
import collections, json, random

QZ = {}


def P(id, title, summary, body, examples):
    return {"id": id, "title": title, "summary": summary, "body": body, "examples": examples}


def Q(point, prompt, options, notes, explanation, translation=""):
    assert len(options) == len(notes) == 4 and notes[0] == "" and len(set(options)) == 4, prompt
    return {"point": point, "prompt": prompt, "options": options, "answer": 0,
            "explanation": explanation, "notes": notes, "translation": translation}


def quiz(fname, id, title, description, points, questions):
    QZ[fname] = {"id": id, "category": "JLPT N1", "title": title, "description": description,
                 "level": "N1", "points": points, "questions": questions}


def write(folder, seed):
    random.seed(seed)
    for fname, d in QZ.items():
        ids = {p["id"] for p in d["points"]}
        cnt = collections.Counter(q["point"] for q in d["questions"])
        assert set(cnt) == ids and min(cnt.values()) >= 2, (fname, cnt)
        prev = None
        for q in d["questions"]:
            while True:
                perm = list(range(4)); random.shuffle(perm)
                if perm.index(0) != prev:
                    break
            q["options"] = [q["options"][i] for i in perm]; q["notes"] = [q["notes"][i] for i in perm]
            q["answer"] = prev = perm.index(0)
        with open(f"{folder}/{fname}.json", "w", encoding="utf-8") as f:
            f.write(json.dumps(d, ensure_ascii=False, indent=2) + "\n")
        print(f"{fname:22} {len(d['points'])} pts {len(d['questions'])} Q")


