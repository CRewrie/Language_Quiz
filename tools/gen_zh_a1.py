"""Generates quizzes/50_zh_a1/*.json. Compact notation: '汉字/pīnyīn' tokens separated by spaces,
'@A' = position marker, '//' = line break, '**' around a token = bold. Other tokens are copied as-is."""
import json, re, random, collections, sys

def zh(s):
    out = []
    for tok in s.split(" "):
        if not tok: continue
        if tok == "//":
            out.append("\n"); continue
        if tok.startswith("@"):
            out.append(f"［{tok[1:]}］"); continue
        if re.fullmatch(r"[A-Za-zāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜü-]+", tok) and out and out[-1].endswith("}"):
            out[-1] = out[-1][:-1] + " " + tok + "}"; continue
        m = re.match(r"^(\**)([^/*]+)/([^*]+?)(\**)$", tok)
        out.append(f"{m[1]}{{{m[2]}|{m[3]}}}{m[4]}" if m else tok)
    return "".join(out)

def P(id, title, summary, body, examples):
    return {"id": id, "title": title, "summary": summary, "body": body,
            "examples": [[zh(a), b] for a, b in examples]}

def Q(point, prompt, options, notes, explanation, translation="", answer=0, fixed=False, raw_opts=False):
    assert len(options) == len(notes) == 4 and notes[answer] == "", (prompt, notes)
    q = {"point": point, "prompt": prompt, "options": options if raw_opts else [zh(o) for o in options],
         "answer": answer, "explanation": explanation, "notes": notes, "translation": translation}
    if fixed:
        q["fixed_order"] = True
    return q

def pos(point, word, sentence, answer, notes, explanation, translation):
    """HSK-style 'where does the word go?' question."""
    return Q(point, f"Where does **{zh(word)}** go?\n" + zh(sentence), ["A", "B", "C", "D"], notes,
             explanation, translation, answer=answer, fixed=True, raw_opts=True)

def star(sentence_with_blanks, pieces_shown, options, notes, explanation, translation):
    prompt = zh(sentence_with_blanks).replace("＿", "　＿＿　").replace("★", "　★　") + "\n（" + "・".join(zh(p) for p in pieces_shown) + "）"
    return Q("order", prompt, options, notes, explanation, translation)

